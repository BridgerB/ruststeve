//! Rust source for `crates/data/src/generated/`, one file per table, formatted by rustfmt so the
//! committed files are exactly what a rerun writes. Lookups are `match`es and sorted statics with a
//! binary search: no `HashMap` in a core crate (brain/ruststeve/design/determinism-rules.md).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;
use std::process::Command;

use anyhow::{Context, Result, bail, ensure};

use crate::fetch::VERSION;
use crate::model::{Game, Ingredient, PacketSet, Shape};
use crate::probe::Probe;

pub fn header() -> String {
    format!(
        "// @generated by `cargo run -p datagen -- generate` from vanilla {VERSION}. Do not edit:\n\
         // regenerate on a runner (brain/ruststeve/design/datagen.md).\n\n"
    )
}

/// `oak_log` → `OakLog`, `debug/game_test_add_marker` → `DebugGameTestAddMarker`. A name starting
/// with a digit gets an `N` in front.
pub fn pascal(name: &str) -> String {
    let mut out = String::new();
    for part in name.split(|c: char| !c.is_ascii_alphanumeric()) {
        let mut cs = part.chars();
        if let Some(first) = cs.next() {
            out.push(first.to_ascii_uppercase());
            out.extend(cs);
        }
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'N');
    }
    out
}

/// Variant names for a list of names, checked unique.
fn variants(what: &str, names: &[String]) -> Result<Vec<String>> {
    let vs: Vec<String> = names.iter().map(|n| pascal(n)).collect();
    let unique: BTreeSet<&String> = vs.iter().collect();
    ensure!(
        unique.len() == vs.len(),
        "{what}: two names map to one variant"
    );
    Ok(vs)
}

/// A kind enum (`ItemKind`, `BlockKind`, `EntityKind`) over a registry, with `Unknown(u32)` for
/// ids a newer server might send, and its id, name and by-name tables.
fn kind_enum(ty: &str, table: &str, names: &[String]) -> Result<String> {
    let vs = variants(ty, names)?;
    let n = names.len();
    let mut s = String::new();
    writeln!(
        s,
        "/// Every {table} in the registry, by protocol id; `Unknown` is an id this table does not know."
    )?;
    writeln!(
        s,
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]"
    )?;
    writeln!(s, "pub enum {ty} {{")?;
    for v in &vs {
        writeln!(s, "    {v},")?;
    }
    writeln!(s, "    Unknown(u32),")?;
    writeln!(s, "}}\n")?;

    let upper = table.to_uppercase();
    writeln!(s, "/// Every known kind, in id order.")?;
    writeln!(s, "pub static {upper}_KINDS: [{ty}; {n}] = [")?;
    for v in &vs {
        writeln!(s, "    {ty}::{v},")?;
    }
    writeln!(s, "];\n")?;
    writeln!(
        s,
        "/// Registry names without the `minecraft:` namespace, in id order."
    )?;
    writeln!(s, "pub static {upper}_NAMES: [&str; {n}] = [")?;
    for name in names {
        writeln!(s, "    {name:?},")?;
    }
    writeln!(s, "];\n")?;
    let mut by_name: Vec<(&String, &String)> = names.iter().zip(&vs).collect();
    by_name.sort();
    writeln!(s, "/// `(name, kind)` sorted by name, for `from_name`.")?;
    writeln!(s, "static {upper}_BY_NAME: [(&str, {ty}); {n}] = [")?;
    for (name, v) in by_name {
        writeln!(s, "    ({name:?}, {ty}::{v}),")?;
    }
    writeln!(s, "];\n")?;

    writeln!(s, "impl {ty} {{")?;
    writeln!(s, "    /// How many kinds the registry has.")?;
    writeln!(s, "    pub const COUNT: usize = {n};\n")?;
    writeln!(s, "    /// The kind with this protocol id, or `Unknown`.")?;
    writeln!(s, "    pub fn from_id(id: u32) -> Self {{")?;
    writeln!(
        s,
        "        usize::try_from(id).ok().and_then(|i| {upper}_KINDS.get(i)).copied().unwrap_or(Self::Unknown(id))"
    )?;
    writeln!(s, "    }}\n")?;
    writeln!(s, "    /// The protocol id.")?;
    writeln!(s, "    pub fn id(self) -> u32 {{")?;
    writeln!(s, "        match self {{")?;
    for (i, v) in vs.iter().enumerate() {
        writeln!(s, "            Self::{v} => {i},")?;
    }
    writeln!(s, "            Self::Unknown(id) => id,")?;
    writeln!(s, "        }}")?;
    writeln!(s, "    }}\n")?;
    writeln!(
        s,
        "    /// The registry name without its namespace; `None` for `Unknown`."
    )?;
    writeln!(s, "    pub fn name(self) -> Option<&'static str> {{")?;
    writeln!(s, "        if let Self::Unknown(_) = self {{")?;
    writeln!(s, "            return None;")?;
    writeln!(s, "        }}")?;
    writeln!(
        s,
        "        usize::try_from(self.id()).ok().and_then(|i| {upper}_NAMES.get(i)).copied()"
    )?;
    writeln!(s, "    }}\n")?;
    writeln!(
        s,
        "    /// The kind a registry name (without namespace) names."
    )?;
    writeln!(s, "    pub fn from_name(name: &str) -> Option<Self> {{")?;
    writeln!(
        s,
        "        {upper}_BY_NAME.binary_search_by(|(n, _)| (*n).cmp(name)).ok().and_then(|i| {upper}_BY_NAME.get(i)).map(|(_, k)| *k)"
    )?;
    writeln!(s, "    }}")?;
    writeln!(s, "}}")?;
    Ok(s)
}

/// A packet enum for one state and direction: `PlayClientbound`, ids 0..n.
fn packet_enum(set: &PacketSet) -> Result<String> {
    let ty = format!("{}{}", pascal(&set.state), pascal(&set.direction));
    let vs = variants(&ty, &set.names)?;
    let mut s = String::new();
    writeln!(
        s,
        "/// Packets in the {} state, {}, by protocol id.",
        set.state, set.direction
    )?;
    writeln!(
        s,
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]"
    )?;
    writeln!(s, "pub enum {ty} {{")?;
    for v in &vs {
        writeln!(s, "    {v},")?;
    }
    writeln!(s, "}}\n")?;
    writeln!(s, "impl {ty} {{")?;
    writeln!(s, "    /// Every packet, in id order.")?;
    writeln!(s, "    pub const ALL: &'static [Self] = &[")?;
    for v in &vs {
        writeln!(s, "        Self::{v},")?;
    }
    writeln!(s, "    ];\n")?;
    writeln!(s, "    /// The packet with this id, if the table has it.")?;
    writeln!(s, "    pub fn from_id(id: u32) -> Option<Self> {{")?;
    writeln!(
        s,
        "        usize::try_from(id).ok().and_then(|i| Self::ALL.get(i)).copied()"
    )?;
    writeln!(s, "    }}\n")?;
    writeln!(s, "    /// The protocol id.")?;
    writeln!(s, "    pub fn id(self) -> u32 {{")?;
    writeln!(s, "        match self {{")?;
    for (i, v) in vs.iter().enumerate() {
        writeln!(s, "            Self::{v} => {i},")?;
    }
    writeln!(s, "        }}")?;
    writeln!(s, "    }}\n")?;
    writeln!(s, "    /// Mojang's name without the namespace.")?;
    writeln!(s, "    pub fn name(self) -> &'static str {{")?;
    writeln!(s, "        match self {{")?;
    for (v, name) in vs.iter().zip(&set.names) {
        writeln!(s, "            Self::{v} => {name:?},")?;
    }
    writeln!(s, "        }}")?;
    writeln!(s, "    }}")?;
    writeln!(s, "}}\n")?;
    Ok(s)
}

fn version_rs(g: &Game) -> Result<String> {
    let v = &g.version;
    let mut s = header();
    writeln!(s, "use crate::types::Version;\n")?;
    writeln!(
        s,
        "/// The server version every table here was generated from (its `version.json`)."
    )?;
    writeln!(
        s,
        "pub static VERSION: Version = Version {{ id: {:?}, protocol: {}, world: {}, java: {} }};",
        v.id, v.protocol, v.world, v.java
    )?;
    Ok(s)
}

fn packets_rs(g: &Game) -> Result<String> {
    let mut s = header();
    for set in &g.packets {
        s.push_str(&packet_enum(set)?);
    }
    Ok(s)
}

fn blocks_rs(g: &Game) -> Result<String> {
    let names: Vec<String> = g.blocks.iter().map(|b| b.name.clone()).collect();
    let vs = variants("BlockKind", &names)?;
    let mut s = header();
    writeln!(s, "use crate::types::{{BlockInfo, Property}};\n")?;
    s.push_str(&kind_enum("BlockKind", "block", &names)?);
    let n = g.blocks.len();
    writeln!(
        s,
        "\n/// Every block's state ids and properties, by block id."
    )?;
    writeln!(s, "pub static BLOCKS: [BlockInfo; {n}] = [")?;
    for b in &g.blocks {
        write!(
            s,
            "    BlockInfo {{ name: {:?}, first_state: {}, last_state: {}, default_state: {}, properties: &[",
            b.name, b.first_state, b.last_state, b.default_state
        )?;
        for (name, values) in &b.properties {
            write!(s, "Property {{ name: {name:?}, values: &[")?;
            for v in values {
                write!(s, "{v:?}, ")?;
            }
            write!(s, "] }}, ")?;
        }
        writeln!(s, "] }},")?;
    }
    writeln!(s, "];\n")?;
    let mut by_state: Vec<(u64, &String)> =
        g.blocks.iter().map(|b| b.first_state).zip(&vs).collect();
    by_state.sort();
    writeln!(
        s,
        "/// `(first state id, block)` sorted by state id, for `block_of_state`."
    )?;
    writeln!(s, "static BY_STATE: [(u32, BlockKind); {n}] = [")?;
    for (first, v) in by_state {
        writeln!(s, "    ({first}, BlockKind::{v}),")?;
    }
    writeln!(s, "];\n")?;
    let states = g.blocks.iter().map(|b| b.last_state + 1).max().unwrap_or(0);
    writeln!(
        s,
        "/// How many block states there are: ids run 0..STATE_COUNT."
    )?;
    writeln!(s, "pub const STATE_COUNT: u32 = {states};\n")?;
    writeln!(
        s,
        "/// The block a state id belongs to; `None` past the last state."
    )?;
    writeln!(
        s,
        "pub fn block_of_state(state: u32) -> Option<BlockKind> {{"
    )?;
    writeln!(s, "    if state >= STATE_COUNT {{")?;
    writeln!(s, "        return None;")?;
    writeln!(s, "    }}")?;
    writeln!(
        s,
        "    let i = BY_STATE.partition_point(|(first, _)| *first <= state);"
    )?;
    writeln!(
        s,
        "    i.checked_sub(1).and_then(|i| BY_STATE.get(i)).map(|(_, b)| *b)"
    )?;
    writeln!(s, "}}\n")?;
    writeln!(s, "impl BlockKind {{")?;
    writeln!(
        s,
        "    /// The block's state ids and properties; `None` for `Unknown`."
    )?;
    writeln!(s, "    pub fn info(self) -> Option<&'static BlockInfo> {{")?;
    writeln!(s, "        if let Self::Unknown(_) = self {{")?;
    writeln!(s, "            return None;")?;
    writeln!(s, "        }}")?;
    writeln!(
        s,
        "        usize::try_from(self.id()).ok().and_then(|i| BLOCKS.get(i))"
    )?;
    writeln!(s, "    }}")?;
    writeln!(s, "}}")?;
    Ok(s)
}

fn simple_kind_rs(ty: &str, table: &str, names: &[String]) -> Result<String> {
    let mut s = header();
    s.push_str(&kind_enum(ty, table, names)?);
    Ok(s)
}

fn registries_rs(g: &Game) -> Result<String> {
    let mut s = header();
    let mut table = |name: &str, doc: &str, names: &[String]| -> Result<()> {
        writeln!(s, "/// {doc}")?;
        writeln!(
            s,
            "pub static {}: [&str; {}] = [",
            name.to_uppercase(),
            names.len()
        )?;
        for n in names {
            writeln!(s, "    {n:?},")?;
        }
        writeln!(s, "];\n")?;
        Ok(())
    };
    for (name, reg) in &g.registries {
        table(
            name,
            &format!("The `minecraft:{name}` registry, by protocol id (the wire sends the index)."),
            &reg.names,
        )?;
    }
    table(
        "damage_type",
        "Damage types sorted by name: the order the server syncs the registry in (a damage event names one by index).",
        &g.damage_types,
    )?;
    table(
        "biome",
        "Biomes sorted by name: the order the server syncs the registry in (a chunk's biome palette holds these indexes).",
        &g.biomes,
    )?;
    Ok(s)
}

fn tags_rs(g: &Game) -> Result<String> {
    let mut s = header();
    writeln!(s, "use super::blocks::BlockKind;")?;
    writeln!(s, "use super::items::ItemKind;\n")?;
    let mut tags =
        |name: &str, ty: &str, doc: &str, map: &BTreeMap<String, BTreeSet<String>>| -> Result<()> {
            writeln!(s, "/// {doc}")?;
            writeln!(s, "pub static {name}: [(&str, &[{ty}]); {}] = [", map.len())?;
            for (tag, values) in map {
                write!(s, "    ({tag:?}, &[")?;
                for v in values {
                    write!(s, "{ty}::{}, ", pascal(v))?;
                }
                writeln!(s, "]),")?;
            }
            writeln!(s, "];\n")?;
            Ok(())
        };
    tags(
        "ITEM_TAGS",
        "ItemKind",
        "Item tags sorted by name, nested tags resolved.",
        &g.item_tags,
    )?;
    tags(
        "BLOCK_TAGS",
        "BlockKind",
        "Block tags sorted by name, nested tags resolved.",
        &g.block_tags,
    )?;
    writeln!(
        s,
        "/// The items an item tag (without namespace, e.g. `planks`) holds."
    )?;
    writeln!(
        s,
        "pub fn item_tag(name: &str) -> Option<&'static [ItemKind]> {{"
    )?;
    writeln!(
        s,
        "    ITEM_TAGS.binary_search_by(|(n, _)| (*n).cmp(name)).ok().and_then(|i| ITEM_TAGS.get(i)).map(|(_, v)| *v)"
    )?;
    writeln!(s, "}}\n")?;
    writeln!(
        s,
        "/// The blocks a block tag (without namespace, e.g. `mineable/pickaxe`) holds."
    )?;
    writeln!(
        s,
        "pub fn block_tag(name: &str) -> Option<&'static [BlockKind]> {{"
    )?;
    writeln!(
        s,
        "    BLOCK_TAGS.binary_search_by(|(n, _)| (*n).cmp(name)).ok().and_then(|i| BLOCK_TAGS.get(i)).map(|(_, v)| *v)"
    )?;
    writeln!(s, "}}")?;
    Ok(s)
}

fn small(what: &str, v: u64) -> Result<u8> {
    u8::try_from(v).with_context(|| format!("{what}: {v} does not fit a u8"))
}

fn recipes_rs(g: &Game) -> Result<String> {
    // Every distinct ingredient set once, as a static the recipes point at.
    let mut sets: BTreeMap<&Ingredient, usize> = BTreeMap::new();
    let all = g
        .recipes
        .iter()
        .flat_map(|r| match &r.shape {
            Shape::Shaped { cells, .. } => cells.iter().flatten().collect::<Vec<_>>(),
            Shape::Shapeless { ingredients } => ingredients.iter().collect(),
        })
        .chain(g.smelting.iter().map(|x| &x.input));
    for i in all {
        let next = sets.len();
        sets.entry(i).or_insert(next);
    }
    let mut s = header();
    writeln!(s, "use super::items::ItemKind;")?;
    writeln!(s, "use crate::types::{{Recipe, Shape, Smelt}};\n")?;
    let mut ordered: Vec<(&&Ingredient, &usize)> = sets.iter().collect();
    ordered.sort_by_key(|(_, i)| **i);
    for (set, i) in ordered {
        write!(s, "static ING_{i}: [ItemKind; {}] = [", set.len())?;
        for item in *set {
            write!(s, "ItemKind::{}, ", pascal(item))?;
        }
        writeln!(s, "];")?;
    }
    let ing = |i: &Ingredient| -> Result<String> {
        let n = sets.get(i).context("ingredient not interned")?;
        Ok(format!("&ING_{n}"))
    };
    writeln!(
        s,
        "\n/// Every shaped and shapeless crafting recipe, sorted by id; shaped patterns trimmed like vanilla."
    )?;
    writeln!(s, "pub static RECIPES: [Recipe; {}] = [", g.recipes.len())?;
    for r in &g.recipes {
        let shape = match &r.shape {
            Shape::Shaped {
                width,
                height,
                cells,
            } => {
                let mut c = String::new();
                for cell in cells {
                    match cell {
                        Some(i) => write!(c, "Some({}), ", ing(i)?)?,
                        None => c.push_str("None, "),
                    }
                }
                format!(
                    "Shape::Shaped {{ width: {}, height: {}, cells: &[{c}] }}",
                    small(&r.id, *width as u64)?,
                    small(&r.id, *height as u64)?
                )
            }
            Shape::Shapeless { ingredients } => {
                let mut c = String::new();
                for i in ingredients {
                    write!(c, "{}, ", ing(i)?)?;
                }
                format!("Shape::Shapeless {{ ingredients: &[{c}] }}")
            }
        };
        writeln!(
            s,
            "    Recipe {{ id: {:?}, result: ItemKind::{}, count: {}, shape: {shape} }},",
            r.id,
            pascal(&r.result),
            small(&r.id, r.count)?
        )?;
    }
    writeln!(s, "];\n")?;
    writeln!(s, "/// Every furnace recipe, sorted by id.")?;
    writeln!(s, "pub static SMELTING: [Smelt; {}] = [", g.smelting.len())?;
    for x in &g.smelting {
        writeln!(
            s,
            "    Smelt {{ id: {:?}, input: {}, result: ItemKind::{}, count: {}, ticks: {} }},",
            x.id,
            ing(&x.input)?,
            pascal(&x.result),
            small(&x.id, x.count)?,
            x.ticks
        )?;
    }
    writeln!(s, "];")?;
    Ok(s)
}

fn block_ids(g: &Game) -> BTreeMap<&str, usize> {
    g.blocks
        .iter()
        .enumerate()
        .map(|(i, b)| (b.name.as_str(), i))
        .collect()
}

/// A block's loot tries: `(item, chance)` in the order the game tries them.
type Tries = Vec<(String, f64)>;

fn loot_rs(g: &Game) -> Result<String> {
    let ids = block_ids(g);
    let mut rows: Vec<(usize, &String, &Tries)> = Vec::new();
    for (block, tries) in &g.drops {
        let id = *ids
            .get(block.as_str())
            .with_context(|| format!("loot: no block {block}"))?;
        rows.push((id, block, tries));
    }
    rows.sort_by_key(|r| r.0);
    let mut s = header();
    writeln!(s, "use super::blocks::BlockKind;")?;
    writeln!(s, "use super::items::ItemKind;")?;
    writeln!(s, "use crate::types::{{BlockDrops, Drop}};\n")?;
    writeln!(
        s,
        "/// Each block's first loot pool for a breaker with no enchanted tool: tried in order, the first"
    )?;
    writeln!(
        s,
        "/// that rolls under its chance drops. Sorted by block id."
    )?;
    writeln!(
        s,
        "pub static BLOCK_DROPS: [BlockDrops; {}] = [",
        rows.len()
    )?;
    for (_, block, tries) in &rows {
        write!(
            s,
            "    BlockDrops {{ block: BlockKind::{}, tries: &[",
            pascal(block)
        )?;
        for (item, chance) in *tries {
            write!(
                s,
                "Drop {{ item: ItemKind::{}, chance: {chance:?} }}, ",
                pascal(item)
            )?;
        }
        writeln!(s, "] }},")?;
    }
    writeln!(s, "];\n")?;
    writeln!(
        s,
        "/// What breaking a block with a plain tool can drop; empty when nothing does."
    )?;
    writeln!(s, "pub fn drops_of(block: BlockKind) -> &'static [Drop] {{")?;
    writeln!(
        s,
        "    BLOCK_DROPS.binary_search_by_key(&block.id(), |d| d.block.id()).ok().and_then(|i| BLOCK_DROPS.get(i)).map_or(&[], |d| d.tries)"
    )?;
    writeln!(s, "}}")?;
    Ok(s)
}

fn harvest_rs(g: &Game) -> Result<String> {
    let ids = block_ids(g);
    let mut rows = Vec::new();
    for (block, h) in &g.harvest {
        let id = *ids
            .get(block.as_str())
            .with_context(|| format!("harvest: no block {block}"))?;
        rows.push((id, block, h));
    }
    rows.sort_by_key(|r| r.0);
    let opt =
        |o: Option<&str>, ty: &str| o.map_or("None".to_owned(), |v| format!("Some({ty}::{v})"));
    let mut s = header();
    writeln!(s, "use super::blocks::BlockKind;")?;
    writeln!(s, "use crate::types::{{Harvest, Tier, ToolKind}};\n")?;
    writeln!(
        s,
        "/// From the `mineable/*` and `needs_*_tool` block tags, sorted by block id. A block not here"
    )?;
    writeln!(
        s,
        "/// is mined at the same speed by anything and drops to a hand."
    )?;
    writeln!(s, "pub static HARVEST: [Harvest; {}] = [", rows.len())?;
    for (_, block, h) in &rows {
        writeln!(
            s,
            "    Harvest {{ block: BlockKind::{}, tool: {}, needs: {} }},",
            pascal(block),
            opt(h.tool, "ToolKind"),
            opt(h.needs, "Tier")
        )?;
    }
    writeln!(s, "];\n")?;
    writeln!(
        s,
        "/// The tool kind that mines a block faster and the tier it needs, if any."
    )?;
    writeln!(
        s,
        "pub fn harvest_of(block: BlockKind) -> Option<&'static Harvest> {{"
    )?;
    writeln!(
        s,
        "    HARVEST.binary_search_by_key(&block.id(), |h| h.block.id()).ok().and_then(|i| HARVEST.get(i))"
    )?;
    writeln!(s, "}}")?;
    Ok(s)
}

fn dimensions_rs(g: &Game) -> Result<String> {
    let mut s = header();
    writeln!(s, "use crate::types::DimensionType;\n")?;
    writeln!(
        s,
        "/// Dimension types sorted by name, the registry order the server sends them in: `id` is the"
    )?;
    writeln!(
        s,
        "/// index a login or respawn names its dimension type by."
    )?;
    writeln!(
        s,
        "pub static DIMENSION_TYPES: [DimensionType; {}] = [",
        g.dimensions.len()
    )?;
    for (i, d) in g.dimensions.iter().enumerate() {
        ensure!(
            d.height % 16 == 0,
            "{}: height {} is not whole sections",
            d.name,
            d.height
        );
        writeln!(
            s,
            "    DimensionType {{ name: {:?}, id: {i}, min_y: {}, height: {}, sections: {}, logical_height: {}, coordinate_scale: {:?} }},",
            d.name,
            d.min_y,
            d.height,
            d.height / 16,
            d.logical_height,
            d.coordinate_scale
        )?;
    }
    writeln!(s, "];")?;
    Ok(s)
}

/// Write every table into `out` (replacing what is there) and rustfmt the files.
pub fn write_all(g: &Game, p: &Probe, out: &Path) -> Result<()> {
    if out.exists() {
        std::fs::remove_dir_all(out).with_context(|| format!("clear {}", out.display()))?;
    }
    std::fs::create_dir_all(out).with_context(|| format!("create {}", out.display()))?;
    let files: Vec<(&str, String)> = vec![
        ("blocks", blocks_rs(g)?),
        ("dimensions", dimensions_rs(g)?),
        (
            "entities",
            simple_kind_rs("EntityKind", "entity", &g.entities.names)?,
        ),
        ("harvest", harvest_rs(g)?),
        ("items", simple_kind_rs("ItemKind", "item", &g.items.names)?),
        ("loot", loot_rs(g)?),
        ("packets", packets_rs(g)?),
        ("recipes", recipes_rs(g)?),
        ("registries", registries_rs(g)?),
        ("tags", tags_rs(g)?),
        ("version", version_rs(g)?),
        ("hardness", crate::emit_probe::hardness_rs(g, p)?),
        ("shapes", crate::emit_probe::shapes_rs(g, p)?),
        ("tools", crate::emit_probe::tools_rs(p)?),
        ("fuel", crate::emit_probe::fuel_rs(g, p)?),
        ("mobs", crate::emit_probe::mobs_rs(g, p)?),
        ("metadata", crate::emit_probe::metadata_rs(p)?),
    ];
    let mut modules: Vec<&str> = files.iter().map(|(n, _)| *n).collect();
    modules.sort_unstable();
    let mut paths = Vec::new();
    for (name, text) in files {
        let path = out.join(format!("{name}.rs"));
        std::fs::write(&path, text).with_context(|| format!("write {}", path.display()))?;
        paths.push(path);
    }
    let mut module = header();
    for m in modules {
        writeln!(module, "pub mod {m};")?;
    }
    let mod_path = out.join("mod.rs");
    std::fs::write(&mod_path, module)?;
    paths.push(mod_path);

    let status = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .args(&paths)
        .status()
        .context("run rustfmt")?;
    if !status.success() {
        bail!("rustfmt failed on the generated files: {status}");
    }
    Ok(())
}
